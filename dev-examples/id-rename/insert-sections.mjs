// 向需求覆盖与补齐文档插入「两种原子化」「优先级」两节并重排章节号（一次性，2026-11-24）
import fs from "node:fs";

const f = "dev-docs/design/2026-11-24-RuleStudio需求覆盖与补齐.md";
let s = fs.readFileSync(f, "utf8");

const ZHI = ["一", "二", "三", "四", "五", "六", "七", "八", "九", "十", "十一", "十二", "十三", "十四", "十五", "十六", "十七", "十八", "十九", "二十"];

const SEC_TWO = `## 二、两条支线：规则原子与需求原子的分工

这一功能**不是**与规则结构化并列的另一条开发线路。两者从同一份原始资料出发，产物与目的不同，最后在覆盖分析处汇合：

- **A 线（规则结构化，已有，主线基础设施）**：把原始资料转成规则卡、配置项、未决项。
- **B 线（需求原子化，新增，质量检查层）**：把原始资料拆成可追踪的最小需求单元，用来验证 A 线的结果有没有遗漏。

两条线都涉及「原子化」，但原子化的**对象不同**：

| 对比 | 规则原子化（A 线，已有） | 需求原子化（B 线，新增） |
| --- | --- | --- |
| 拆解对象 | 规则行为 | 原始资料中的要求 |
| 拆解依据 | 业务逻辑与规则类型（11 类槽位） | 原文段落、表格行、条件分支 |
| 产物 | 规则卡、配置项、未决项 | 原子需求清单 |
| ID 示例 | \`HJ-R-CHENGBAO\`、\`HJ-F-ZHUANGXIAN-BEILV\` | \`HZ-R-001\`、\`HZ-F-001\` |
| 目的 | 让规则可查询、可编译、可复用 | 让每项原始要求都能被追踪与验收 |
| 解决的问题 | 规则如何组织 | 有没有漏掉规则 |

### 举例（原文 2.3.3 自摸一行）

> 闲家自摸时，庄家一笔乘 8，另两个闲家各乘 1。

- **规则原子化**：写成 \`HJ-F-ZHUANGXIAN-BEILV\`（庄闲倍率）里的完整计算规则。
- **需求原子化**：拆成 \`HZ-F-001\`（闲家自摸时庄家一笔乘 8）、\`HZ-F-002\`（另两名闲家各乘 1）。

两条需求都映射到同一张规则卡。所以 A 与 B 之间是**多对多**关系，不是一对一。

### 必须坚持的原则（否则功能失效）

**B 线必须独立从 \`sources/\` 提取需求，不能从 A 线已生成的规则卡反向拆需求。**

理由很直接：如果某一要求被 A 线漏掉了，从规则卡反推出来的需求清单也会跟着漏掉，于是「覆盖分析」永远报不出这个遗漏 —— 功能等于自证清白。

同理，覆盖判定只能**拿需求去查规则库**，不能**拿规则卡去生成需求**。

### 分工与优先级结论

结构化是基础设施，需求覆盖与补齐是质量保障。当前不应继续投入扩展结构化能力，而应把精力转向覆盖与补齐（见下节）。

`;

const SEC_THREE = `## 三、开发优先级

| 优先级 | 功能 | 决策 |
| --- | --- | --- |
| P0 | 现有规则结构化体系（11 类槽位、Schema、Validator、Compiler、杭州 61 卡、萧山 47 卡） | **保持，不重做** |
| P1 | 原子需求拆解（直接读 \`sources/\`） | 新增 |
| P2 | 需求与规则卡 / 配置项映射（多对多） | 新增 |
| P3 | 覆盖状态分析（六态） | 新增 |
| P4 | 补齐建议生成（明确目标文件与内容要点） | 新增 |
| P5 | 补齐转提案 | 复用既有提案机制，不新建 |

为什么这样排：现在已经有 61 张杭州卡、25 项杭州配置（20 玩法 + 5 界面）、47 张萧山卡、Schema / Validator / Compiler、章节级 \`coverage.md\`。**缺的不是结构化工具，而是证明这些产物完整覆盖了原始资料的手段**。继续扩展结构化能力不会让「完整性」变得可证明。

`;

// 插入位置：在原「## 二、现状」之前
const anchor = "## 二、现状：已有的基础与真正缺的东西";
if (!s.includes(anchor)) throw new Error("现状章节未匹配");
s = s.replace(anchor, SEC_TWO + SEC_THREE + "## 三、现状：已有的基础与真正缺的东西");

// ── 重排其余章节号（跳过附录）──
const lines = s.split("\n");
let n = 0;
const re = /^## (一|二|三|四|五|六|七|八|九|十|十一|十二|十三|十四|十五|十六|十七|十八|十九|二十)、/;
for (let i = 0; i < lines.length; i++) {
  if (re.test(lines[i])) {
    lines[i] = lines[i].replace(re, `## ${ZHI[n]}、`);
    n++;
  }
}
s = lines.join("\n");
fs.writeFileSync(f, s);
console.log(`重排完成，共 ${n} 个编号章节`);
